"""Keeping each strategy's concept document pointing at its newest artefacts.

A mounted strategy repository documents every strategy in
``docs/concepts/<strategy>.md``, and that document is written by hand. What it
cannot state by hand is where the *current* evidence lives: a replay writes its
JSON, its Markdown and its HTML dashboard into
``data/reports/<session>/`` in the engine checkout, under a timestamped name,
and the next replay writes another one beside it. Whoever reads the concept
document a week later has no way to tell which of them was the run the defaults
are standing on.

So the engine appends one machine-owned section to the bottom of the document
and rewrites it on every reporting run. Three decisions worth stating:

* **The block is delimited, not located.** Everything between
  :data:`BEGIN_MARKER` and :data:`END_MARKER` belongs to this module and is
  replaced wholesale; everything outside them is the author's and is never
  touched. That is what makes the rewrite safe to run unattended, and it is why
  the block carries a visible "do not edit" notice: a hand edit inside it is
  silently lost at the next run.
* **The alias is read out of the document, not derived from its filename.**
  Each concept document opens with ``# <ALIAS>``, so the mapping from a strategy
  to its document is a fact in the document rather than a naming convention
  this repository would have to keep in step with a repository it cannot see.
* **Failure here never fails a backtest.** The replay is the expensive part and
  the report on disk is the artefact; a read-only mount, a missing document or
  a strategy with no document at all is logged and stepped over.

The engine is public and the strategy repositories are not, so nothing in this
module knows a strategy name, a default or a result: it is handed a report and
a mount point and writes what it finds.
"""

from __future__ import annotations

import json
import os
import re
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from qte_shared.config import REPO_ROOT, settings
from qte_shared.logging_setup import get_logger

log = get_logger(__name__)

#: Opens the machine-owned block. Both markers are HTML comments so they render
#: as nothing, and both are matched literally — never regenerate them with a
#: different spelling, or the next run appends a second block instead of
#: replacing this one.
BEGIN_MARKER = "<!-- QTE-LATEST-ARTEFACTS:BEGIN -->"
END_MARKER = "<!-- QTE-LATEST-ARTEFACTS:END -->"

HEADING = "## Latest artefacts"

_WARNING = (
    "> **Auto-generated — do not edit.** Everything between the two\n"
    "> `QTE-LATEST-ARTEFACTS` markers is rewritten by the engine on the next\n"
    "> `qte-backtest run --report` of this strategy. A hand edit here is lost;\n"
    "> put the prose in the sections above instead.\n"
)

_PROVENANCE = (
    "<!--\n"
    "  AUTO-GENERATED by qte_backtest.doc_reference, from the engine checkout.\n"
    "  Rewritten wholesale on every `qte-backtest run --report` of this\n"
    "  strategy, and by `qte-backtest doc-reference`. Do not edit this block,\n"
    "  do not reorder it, and do not move the markers around it.\n"
    "-->\n"
)

_EMPTY_BODY = (
    "No reporting replay has been recorded here yet. The next\n"
    "`qte-backtest run --report <DIR>` of this strategy fills this block in.\n"
)

#: The ``# <ALIAS>`` a concept document opens with.
_TITLE_PATTERN = re.compile(r"^#\s+(?P<alias>[A-Z][A-Z0-9_]{5,})\s*$", re.M)

#: Which report format goes in which row, in the order a reader wants them: the
#: page first, because it is the one a human opens.
_FORMAT_ROWS: tuple[tuple[str, str], ...] = (
    ("html", "Dashboard"),
    ("md", "Report"),
    ("json", "JSON"),
)


@dataclass(slots=True, frozen=True)
class ArtefactReference:
    """What the block states: one replay and the files it left behind."""

    strategy: str
    symbol: str
    timeframe: str
    generated_at: datetime | None = None
    period_start: str | None = None
    period_end: str | None = None
    #: Format name (``json``, ``md``, ``html``) to the file written.
    reports: Mapping[str, Path] = field(default_factory=dict)
    #: The newest write-up under ``data/audits/`` that names this strategy.
    audit: Path | None = None
    #: The few numbers that decide whether the run is worth opening at all.
    headline: str | None = None


# ── Finding the documents ─────────────────────────────────────────────


def concept_documents(strategies_dir: Path | None = None) -> dict[str, Path]:
    """Map every published alias to the concept document that opens with it.

    Scans ``<mount>/*/docs/concepts/*.md`` only — the convention every mounted
    repository follows — rather than walking the mount, which holds checkouts,
    virtualenvs and build trees.
    """
    mount = Path(strategies_dir or settings.engine.strategies_dir)
    found: dict[str, Path] = {}
    if not mount.is_dir():
        return found
    for document in sorted(mount.glob("*/docs/concepts/*.md")):
        if document.name == "README.md":
            continue
        try:
            head = document.read_text(encoding="utf-8")[:4096]
        except OSError as error:
            log.warning("Could not read %s: %s", document, error)
            continue
        title = _TITLE_PATTERN.search(head)
        if title is None:
            continue
        found.setdefault(title.group("alias"), document)
    return found


def latest_audit(strategy: str, audits_dir: Path | None = None) -> Path | None:
    """The newest ``data/audits/YYYY-MM-DD-<topic>.md`` that names *strategy*.

    Audits are filed by topic, not by strategy, so the only honest link between
    the two is the alias appearing in the text. Dated filenames sort
    chronologically, which is why the newest is the last one by name.
    """
    directory = Path(audits_dir or settings.engine.audits_dir)
    if not directory.is_dir():
        return None
    for candidate in sorted(directory.glob("*.md"), reverse=True):
        try:
            if strategy in candidate.read_text(encoding="utf-8", errors="ignore"):
                return candidate
        except OSError as error:
            log.debug("Could not read %s: %s", candidate, error)
    return None


# ── Rendering ─────────────────────────────────────────────────────────


def render_block(reference: ArtefactReference | None, document: Path) -> str:
    """The whole machine-owned block, markers included.

    *document* is where the block will live, so every path can be written as a
    link relative to it and stay clickable in an editor.
    """
    lines = [BEGIN_MARKER, "", HEADING, "", _PROVENANCE.rstrip(), "", _WARNING.rstrip(), ""]
    if reference is None:
        lines += [_EMPTY_BODY.rstrip(), "", END_MARKER, ""]
        return "\n".join(lines)

    rows: list[tuple[str, str]] = [
        ("Replayed", _replay_summary(reference)),
    ]
    if reference.generated_at is not None:
        rows.append(("Run at", f"{reference.generated_at:%Y-%m-%d %H:%M} UTC"))
    if reference.headline:
        rows.append(("Headline", reference.headline))
    for fmt, label in _FORMAT_ROWS:
        path = reference.reports.get(fmt)
        if path is not None:
            rows.append((label, _link(Path(path), document)))
    rows.append(
        (
            "Audit",
            _link(reference.audit, document)
            if reference.audit is not None
            else "_none under `data/audits/` names this strategy_",
        )
    )

    lines += ["| | |", "| --- | --- |"]
    lines += [f"| {label} | {value} |" for label, value in rows]
    lines += ["", END_MARKER, ""]
    return "\n".join(lines)


def _replay_summary(reference: ArtefactReference) -> str:
    period = ""
    if reference.period_start and reference.period_end:
        period = f", {_day(reference.period_start)} → {_day(reference.period_end)}"
    return f"`{reference.symbol}` {reference.timeframe}{period}"


def _day(stamp: str) -> str:
    return stamp[:10]


def _link(path: Path | None, document: Path) -> str:
    """A markdown link to *path*, labelled by where it sits in the checkout.

    The label is the engine-relative path, because that is how a report is
    named in a changelog entry or a chat message; the target is relative to the
    document, because that is what an editor can follow.
    """
    if path is None:
        return "—"
    resolved = Path(path).resolve()
    try:
        label = resolved.relative_to(REPO_ROOT.resolve()).as_posix()
    except ValueError:
        label = resolved.as_posix()
    try:
        target = Path(os.path.relpath(resolved, document.resolve().parent)).as_posix()
    except ValueError:
        # A different drive on Windows: no relative path exists.
        target = resolved.as_uri()
    return f"[`{label}`]({target})"


# ── Writing ───────────────────────────────────────────────────────────


def apply_block(text: str, block: str) -> str:
    """Replace the machine-owned block in *text*, or append it at the bottom.

    Anything outside the markers is returned untouched, including a trailing
    section an author put after an earlier block — the block is replaced where
    it already is rather than forced back to the end of the file.
    """
    start = text.find(BEGIN_MARKER)
    end = text.find(END_MARKER)
    if start != -1 and end != -1 and end > start:
        head = text[:start]
        tail = text[end + len(END_MARKER) :]
        return head + block.rstrip("\n") + "\n" + tail.lstrip("\n")
    body = text.rstrip("\n")
    appended = block.rstrip("\n")
    return f"{body}\n\n{appended}\n"


def update_concept_document(
    strategy: str,
    reference: ArtefactReference | None,
    *,
    strategies_dir: Path | None = None,
    documents: Mapping[str, Path] | None = None,
) -> Path | None:
    """Rewrite *strategy*'s block, and return the document written.

    ``None`` means there was nothing to write to, or writing failed — both are
    logged. A backtest is never failed by this.
    """
    index = documents if documents is not None else concept_documents(strategies_dir)
    document = index.get(strategy)
    if document is None:
        log.debug("No concept document found for %s; its artefact block is skipped", strategy)
        return None
    try:
        text = document.read_text(encoding="utf-8")
        updated = apply_block(text, render_block(reference, document))
        if updated != text:
            document.write_text(updated, encoding="utf-8")
            log.info("Updated the latest-artefact block in %s", document)
    except OSError as error:
        log.warning("Could not update %s: %s", document, error)
        return None
    return document


def reference_from_report(
    report: Any,
    written: Sequence[Path],
    *,
    audits_dir: Path | None = None,
) -> ArtefactReference:
    """Turn a :class:`~qte_backtest.report.BacktestReport` into a reference."""
    result = report.result
    metrics = result.metrics
    return ArtefactReference(
        strategy=result.strategy,
        symbol=result.symbol,
        timeframe=result.timeframe,
        generated_at=report.generated_at,
        period_start=_iso(getattr(metrics, "period_start", None)),
        period_end=_iso(getattr(metrics, "period_end", None)),
        reports=_by_format(written),
        audit=latest_audit(result.strategy, audits_dir),
        headline=_headline(metrics.to_dict()),
    )


def record_report(
    report: Any,
    written: Sequence[Path],
    *,
    strategies_dir: Path | None = None,
    audits_dir: Path | None = None,
) -> Path | None:
    """Point this strategy's concept document at the report just written."""
    try:
        reference = reference_from_report(report, written, audits_dir=audits_dir)
    except Exception as error:  # noqa: BLE001 - never fail a finished replay
        log.warning("Could not describe the report for the concept document: %s", error)
        return None
    return update_concept_document(reference.strategy, reference, strategies_dir=strategies_dir)


def reference_from_report_file(
    path: Path,
    *,
    audits_dir: Path | None = None,
) -> ArtefactReference:
    """Read a report JSON written earlier and describe it the same way.

    This is what seeds a document from a replay that happened before the block
    existed; the sibling Markdown and HTML are taken as written if they are
    there.
    """
    document = json.loads(Path(path).read_text(encoding="utf-8"))
    run = document.get("run", {})
    strategy = run.get("strategy")
    if not strategy:
        raise ValueError(f"{path} has no run.strategy; it is not a backtest report")
    data = document.get("data", {})
    siblings = [path.with_suffix(suffix) for suffix in (".json", ".md", ".html")]
    generated = document.get("generated_at")
    return ArtefactReference(
        strategy=strategy,
        symbol=run.get("symbol", "?"),
        timeframe=run.get("timeframe", "?"),
        generated_at=_parsed(generated),
        period_start=data.get("first_bar"),
        period_end=data.get("last_bar"),
        reports=_by_format(existing for existing in siblings if existing.is_file()),
        audit=latest_audit(strategy, audits_dir),
        headline=_headline(document.get("metrics", {})),
    )


# ── Helpers ───────────────────────────────────────────────────────────


def _by_format(written: Iterable[Path]) -> dict[str, Path]:
    return {path.suffix.lstrip("."): path for path in written}


def _headline(metrics: Mapping[str, Any]) -> str | None:
    """The few numbers that say whether the book is worth opening.

    Win rate and the longest losing run are in here beside the net result on
    purpose: a book can be profitable and still be untradeable.
    """
    if not metrics:
        return None
    parts = [
        f"{_number(metrics.get('trades'), 0)} trades",
        f"{_number(metrics.get('win_rate'), 2)}% win rate",
        f"max losing run {_number(metrics.get('max_consecutive_losses'), 0)}",
        f"net {_number(metrics.get('net_pnl'), 2)}",
        f"max drawdown {_number(metrics.get('max_drawdown_pct'), 2)}%",
    ]
    return ", ".join(parts)


def _number(value: Any, digits: int) -> str:
    if value is None:
        return "n/a"
    try:
        return f"{float(value):,.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def _iso(value: Any) -> str | None:
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value) if value else None


def _parsed(stamp: Any) -> datetime | None:
    if not isinstance(stamp, str):
        return None
    try:
        parsed = datetime.fromisoformat(stamp)
    except ValueError:
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=UTC)
